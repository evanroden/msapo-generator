"""Bounded source/generated-result viewing shared by PO and Expense workspaces.

No reader, OCR, external URL, generation, save, download or share action exists
here. Original bytes stay with their current workflow owner. Only disposable
PDF tickets enter session state; existing PreviewStore supplies global budgets.
"""
from __future__ import annotations

from hashlib import sha256
from pathlib import Path
from types import SimpleNamespace
from uuid import uuid4

import streamlit as st

from app.monthly_report_preview_store import STORE
from app.monthly_report_preview_view import render_view, viewport


def reference_pdf(raw: bytes, filename: str) -> bytes:
    """Preserve PDF bytes; create bounded disposable copies for image sources."""
    if not isinstance(raw, bytes) or not raw:
        raise ValueError('No source bytes are available.')
    if raw.startswith(b'%PDF-'):
        return raw
    # Reuse the approved receipt image/frame bounds, without invoking a reader.
    # At most ten frames are normalized once for this disposable source copy.
    from app.expense_report import receipt_attachment_pages
    import fitz
    pages = receipt_attachment_pages(raw, filename)
    with fitz.open() as document:
        for image in pages:
            with fitz.open(stream=image, filetype='jpeg') as source:
                image_pdf = source.convert_to_pdf()
            with fitz.open(stream=image_pdf, filetype='pdf') as page:
                document.insert_pdf(page)
        return document.tobytes(garbage=3, deflate=True)


def _owner(scope: str):
    owners = st.session_state.setdefault('_workspace_reference_owners', {})
    scope = sha256(str(scope).encode()).hexdigest()
    if scope not in owners:
        owners[scope] = {'owner':'reference:' + uuid4().hex, 'entries':{}}
    while len(owners) > 12:
        key = next(iter(owners))
        if key == scope:
            break
        old = owners.pop(key)
        for entry in old['entries'].values():
            if entry.get('ticket'):
                STORE.discard(old['owner'], entry['ticket'])
    return owners[scope]


def render_reference(*, key: str, owner_scope: str, title: str, raw: bytes = b'',
                     filename: str = '', text: str | None = None) -> None:
    """Inspect exact uploaded/generated bytes, or the explicitly approved text.

    Call inside the paired reference container. ``owner_scope`` must identify
    the active draft, not the geometry or content fingerprint. The component
    key must be stable for this source/receipt/stage across layout changes.
    """
    if text is not None or Path(filename).suffix.casefold() in ('.txt','.csv'):
        value = text if text is not None else raw.decode('utf-8',errors='replace')
        st.caption(title)
        st.code(value, language=None, wrap_lines=True)
        return
    if not raw:
        st.caption('The source is unavailable. Your entered details remain editable.')
        return
    state = _owner(owner_scope)
    fingerprint = sha256(raw).hexdigest()
    entry = state['entries'].get(key)
    if entry is None or entry['fingerprint'] != fingerprint:
        if entry and entry.get('ticket'):
            STORE.discard(state['owner'],entry['ticket'])
        entry = {'fingerprint':fingerprint,'ticket':None,'error':''}
        state['entries'][key] = entry
    # Tiny metadata is bounded as well as STORE's shared PDF/raster bytes.
    while len(state['entries']) > 64:
        old_key=next(iter(state['entries']))
        if old_key == key:
            break
        old=state['entries'].pop(old_key)
        if old.get('ticket'):
            STORE.discard(state['owner'],old['ticket'])
    widget_key='workspace_reference_' + key

    def changed():
        value=st.session_state.get(widget_key,{})
        selected=viewport(value.get('viewport'),fingerprint) if isinstance(value,dict) else None
        if selected is not None:
            entry['view']=selected

    @st.fragment
    def surface():
        ticket=entry.get('ticket')
        view=entry.get('view',{'visible':False,'pages':(0,),'dpi':96})
        images=()
        status=''
        if ticket and not STORE.available(state['owner'],ticket):
            ticket=None
            entry['ticket']=None
        if view['visible'] and not ticket and not entry['error']:
            try:
                ticket=STORE.put(state['owner'],SimpleNamespace(pdf=reference_pdf(raw,filename)))
                entry['ticket']=ticket
            except Exception as exc:
                entry['error']=str(exc)[:240] or 'This source cannot be previewed.'
        if ticket:
            status=f'Preview · {ticket.pages} page' + ('s' if ticket.pages != 1 else '')
            if view['visible']:
                indexes=tuple(index for index in view['pages'] if index < ticket.pages) or (0,)
                try:
                    images=STORE.pages(state['owner'],ticket,indexes,dpi=view['dpi']) or ()
                except (OSError,ValueError) as exc:
                    entry['error']=str(exc)[:240]
        if entry['error']:
            st.warning('Preview unavailable: ' + entry['error'])
            if st.button('Retry source preview',key=widget_key+'_retry'):
                entry['error']=''
                st.rerun(scope='fragment')
        render_view(key=widget_key,generation=fingerprint,title=title,ticket=ticket,
                    images=images,status=status,on_change=changed,
                    view_scope=state['owner']+'|'+key+'|'+fingerprint)
    surface()
