"""Streamlit-facing proof that known-value and original-source QA are separate routes."""
from pathlib import Path

import pytest
from streamlit.testing.v1 import AppTest

from app import monthly_report_guided as guided, monthly_report_library as library
from app import monthly_report_testing as qa
from app import monthly_report_qa_fixture as fixture

ACTOR_COOKIE = "a" * 32
SOURCE = """from pathlib import Path
import streamlit as st
from app.monthly_report_testing import isolated
from app.monthly_report_testing_ui import render
from app.monthly_report_ui import _field, _move
with isolated("aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"):
    render("aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", "", _field, _move, Path(st.session_state["_qa_base"]))
"""


def visit(monkeypatch, tmp_path):
    monkeypatch.setenv("EPC_DATA_DIR", str(tmp_path))
    from app import monthly_report_section_preview_ui as section_ui
    monkeypatch.setattr(section_ui, "render_section_preview", lambda *args, **kwargs: None)
    app = AppTest.from_string(SOURCE, default_timeout=30)
    app.session_state["_qa_base"] = str(tmp_path)
    app.run()
    assert not app.exception
    assert any("ISOLATED SYNTHETIC TESTING" in x.value for x in app.warning)
    return app


def test_prefill_and_original_replay_appear_as_distinct_editable_ui_actions(monkeypatch, tmp_path):
    app = visit(monkeypatch, tmp_path)
    assert any(x.label == "Load known-value report" for x in app.button)
    assert any(x.label == "Replay synthetic source files" for x in app.button)
    next(x for x in app.button if x.label == "Load known-value report").click().run()
    assert not app.exception
    with qa.isolated(ACTOR_COOKIE):
        first = library.load_snapshot(fixture.CONTRACT, fixture.profile().key, fixture.PERIOD)
        assert first is not None and not first.draft.sources
    assert any("Current fixture: known-value prefill" in x.value for x in app.caption)
    next(x for x in app.button if x.label == "Compare fixture facts").click().run()
    assert not app.exception
    assert any("known-value prefill" in x.value for x in app.markdown)
    first_checks = app.session_state["monthly_qa_comparison"]["checks"]
    assert all(first_checks.values()), {name: passed for name, passed in first_checks.items() if not passed}
    next(x for x in app.button if x.label == "Replay synthetic source files").click().run()
    assert not app.exception
    with qa.isolated(ACTOR_COOKIE):
        second = library.load_snapshot(fixture.CONTRACT, fixture.profile().key, fixture.PERIOD)
        assert second is not None and len(second.draft.sources) == 2
    assert any("Current fixture: original-source replay" in x.value for x in app.caption)
    next(x for x in app.button if x.label == "Compare fixture facts").click().run()
    assert not app.exception
    assert any("source replay" in x.value for x in app.markdown)
    replay_checks = app.session_state["monthly_qa_comparison"]["checks"]
    assert all(replay_checks.values()), {name: passed for name, passed in replay_checks.items() if not passed}


def test_ui_reset_does_not_erase_any_live_report(monkeypatch, tmp_path):
    live = fixture.profile()
    monkeypatch.setenv("EPC_DATA_DIR", str(tmp_path))
    library.save_profile(live, expected_revision=0, actor="Synthetic Live", confirmed=True)
    app = visit(monkeypatch, tmp_path)
    next(x for x in app.button if x.label == "Load known-value report").click().run()
    assert not app.exception
    next(x for x in app.button if x.label == "Reset this test only").click().run()
    assert not app.exception
    with qa.isolated(ACTOR_COOKIE):
        assert library.load_snapshot(fixture.CONTRACT, fixture.profile().key, fixture.PERIOD) is None
    assert library.load_profile(live.contract, live.key).revision == 1



def test_known_value_qa_editor_prefills_synthetic_author_and_generates_both_formats(monkeypatch, tmp_path):
    # A real visitor supplies their own name. An isolated known-value fixture
    # already includes an invented author: verify the actual editor and export,
    # not merely the snapshot or the Compare button.
    # Streamlit defaults download_button clicks to a full rerun, which can
    # cancel a real file transfer. The generated bytes must remain available
    # while both independent browser downloads complete.
    import streamlit as st
    original_download = st.download_button
    downloads = {}
    def verified_download(*args, **kwargs):
        if args and args[0].startswith("Download isolated QA"):
            downloads[args[0]] = kwargs.get("on_click")
        return original_download(*args, **kwargs)
    monkeypatch.setattr(st, "download_button", verified_download)
    app = visit(monkeypatch, tmp_path)
    next(x for x in app.button if x.label == "Load known-value report").click().run()
    assert not app.exception
    prepared = next(w for w in app.text_input if w.label == "Prepared by")
    assert prepared.value == fixture.ACTOR
    next(x for x in app.button if x.label == "Generate QA Word and PDF").click().run()
    assert not app.exception
    assert not any("QA export was blocked" in x.value for x in app.error)
    fingerprint, package = app.session_state["monthly_qa_package"]
    assert package.docx.startswith(b"PK"), package.pdf_error
    assert package.pdf and package.pdf.startswith(b"%PDF-"), package.pdf_error
    assert {b.label for b in app.get("download_button")} >= {
        "Download isolated QA DOCX", "Download isolated QA PDF"}
    assert downloads == {
        "Download isolated QA DOCX": "ignore",
        "Download isolated QA PDF": "ignore",
    }
    assert fingerprint == package.fingerprint



def test_browser_reconnect_returns_to_same_qa_period_and_recovers_activity(monkeypatch, tmp_path):
    from app import monthly_report_active_work as active
    first = visit(monkeypatch, tmp_path)
    next(b for b in first.button if b.label == "Load known-value report").click().run()
    expected = "Synthetic reviewed September pump work, edited before refresh."
    next(w for w in first.text_area if w.label == "Activity summary").set_value(expected).run()
    assert not first.exception
    with qa.isolated(ACTOR_COOKIE):
        journal = active.load(ACTOR_COOKIE, fixture.CONTRACT, fixture.profile().key, fixture.PERIOD)
        assert journal is not None
        assert expected in next(b.text for b in journal.draft.blocks if b.key == "activity_summary")
    from hashlib import sha256
    receipt = "QA durable Activity SHA256: " + sha256(expected.encode("utf-8")).hexdigest()
    assert any(x.value == receipt for x in first.caption), (
        "QA must confirm exact durable content after the editor reruns")

    # A new Streamlit session does not inherit any widget keys, unlike an
    # ordinary app rerun. The real recovery journal still owns the latest edit.
    reopened = visit(monkeypatch, tmp_path)
    assert not reopened.exception
    assert reopened.selectbox("report_month_number").value == fixture.PERIOD.month
    assert reopened.selectbox("report_year").value == fixture.PERIOD.year
    assert next(w for w in reopened.text_area if w.label == "Activity summary").value == expected
    assert next(w for w in reopened.text_input if w.label == "Prepared by").value == fixture.ACTOR
    assert any("Recovered your unfinished changes" in s.value for s in reopened.success)
    assert not reopened.error
